"""Finite, source-only extraction of annual USD facts from supplied filing excerpts.

This module never reads XBRL answers, evaluation labels, or the corpus on disk. Unsupported
layouts remain model fallbacks; contradictory complete facts do not become verified answers.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from decimal import Decimal, InvalidOperation

from . import config
from .chunking import CHUNK_WORDS, OVERLAP_WORDS, Chunk

VERSION = "source-grounded-usd-v11"
SourceLine = tuple[str, str | None]
NONCONTROLLING = re.compile(r"\bnon[ -]?controlling\b", re.I)
YEAR = re.compile(r"(?<!\d)((?:19|20)\d{2})(?!\d)")
MONTH = r"(?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:t(?:ember)?)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?)"
SCALES = {
    "thousand": Decimal(1000),
    "million": Decimal(1000000),
    "billion": Decimal(1000000000),
    "trillion": Decimal(1000000000000),
}
CAPTION = re.compile(
    r"(?:\(|\b)(?:u\.?s\.? dollars? |dollars? |\$ )?in "
    r"(thousands?|millions?|billions?|trillions?)(?:\b|\))",
    re.I,
)
FOREIGN = re.compile(
    r"\b(?:EUR|GBP|JPY|CAD|AUD|NZD|HKD|SGD|MXN|TWD|CNY|CHF|RMB|euros?|pounds?|yen)\b"
    r"|(?<!\w)(?:C|CA|CAN|A|AU|NZ|HK|S|SG|MX|NT)\s*\$"
    r"|\b(?:Canadian|Australian|New Zealand|Hong Kong|Singapore|Mexican|New Taiwan)\s+dollars?\b"
    r"|[€£¥]",
    re.I,
)
QUARTER = re.compile(
    r"\bquarter(?:ly)?\b|\b(?:Q[1-4]|[1-4]Q)(?:[ -]?(?:FY)?(?:\d{4}|\d{2}))?\b|"
    r"\b(?:H[12]|[12]H)(?:[ -]?(?:FY)?(?:\d{4}|\d{2}))?\b|"
    r"\bhalf[ -]year\b|\bsemiannual\b|\b(?:first|second|1st|2nd) half\b|"
    r"\bYTD\b|\byear[ -]to[ -]date\b",
    re.I,
)
QUALIFIED_ENTITY = re.compile(
    r"\bparent\b|\bregistrant\b|\bguarantors?\b|\bconsolidating\b|"
    r"\bdiscontinued operations?\b|\bsubsidiary[ -]only\b|\bpro[ -]forma\b", re.I,
)
ROLLUP = re.compile(
    r"(?:total )?(?:net sales|revenues?|sales) by (?:reportable segments?|category)", re.I
)
STATEMENT = re.compile(
    r"^(?:consolidated (?:statements?|balance sheets?)|balance sheets?|"
    r"income statements?|cash flows? statements?|stockholders.? equity statements?)\b",
    re.I,
)
BOUNDARY = re.compile(
    r"^(?:reportable segments?|operating segments?|segment information|"
    r"operating expenses|end of table)\b|\bsegment$",
    re.I,
)
FOOTNOTE = re.compile(r"\([a-z]\)|\d+\)", re.I)
CELL = re.compile(
    r"[+\-−]?\s*(?:\$\s*)?(?:\(\s*)?(?:\$\s*)?[+\-−]?\s*"
    r"(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?\s*\)?",
    re.I,
)
MONEY = re.compile(
    r"(?:\(\s*)?[+\-−]?\s*\$\s*(?:\(\s*)?"
    r"[+\-−]?\s*\d[\d,]*(?:\.\d+)?\s*\)?\s*"
    r"(?:thousand|million|billion|trillion)s?\b\)?",
    re.I,
)

INTENTS = {
    "operating_cash_flow": r"(?:operating cash flow|cash (?:provided by|used in|from).*operating activities)",
    "rd_expense": r"research and development|r&d",
    "total_assets": r"total assets",
    "operating_income": r"operating income|income from operations",
    "net_income": r"net income|net profit",
    "equity": r"stockholders.? equity|shareholders.? equity|shareowners.? equity",
    "revenue": r"revenue|net sales",
}
LABELS = {
    "revenue": r"(?:total )?(?:net operating revenues?|net revenues?|net sales|revenues?)",
    "net_income": r"(?:consolidated )?net income(?:\s*\(loss\))?",
    "total_assets": r"total assets",
    "rd_expense": r"research and development(?: expenses?)?",
    "operating_income": r"(?:total )?(?:operating income(?:\s*\(loss\))?|income from operations)",
    "equity": r"(?:total )?(?:stockholders.?|shareholders.?|shareowners.?) equity|total equity",
    "operating_cash_flow": r"(?:net cash (?:provided by|used in|from)(?:/| or | and | )*"
    r"(?:\(?used in\)?)? operating activities|operating activities|"
    r"cash generated by operating activities|net cash from\s*(?:\(used in\))?\s*operations)",
}


@dataclass(frozen=True)
class Intent:
    ticker: str
    year: int
    metric: str


@dataclass
class Fact:
    value: Decimal
    unit_step: Decimal
    intent: Intent
    citations: list[str]
    evidence: list[dict]
    kind: str
    priority: int

    def render(self) -> str:
        amount = (
            format(abs(self.value), ",f").rstrip("0").rstrip(".")
            if self.value % 1
            else format(abs(self.value), ",.0f")
        )
        return f"{'-' if self.value < 0 else ''}${amount} [{', '.join(self.citations)}]"


def company_for_question(question: str, chunks: list[Chunk]) -> str | None:
    candidates = {c.ticker for c in chunks} | set(config.DISPLAY_NAMES)
    found = set()
    for ticker in candidates:
        names = [ticker, config.DISPLAY_NAMES.get(ticker, ticker)]
        if any(re.search(r"(?<!\w)" + re.escape(n) + r"(?!\w)", question, re.I) for n in names):
            found.add(ticker)
    return next(iter(found)) if len(found) == 1 else None


def numeric_intent(question: str, chunks: list[Chunk]) -> Intent | None:
    ticker = company_for_question(question, chunks)
    if not ticker:
        return None
    names = {ticker, config.DISPLAY_NAMES.get(ticker, ticker)}
    company = "(?:" + "|".join(re.escape(n) for n in sorted(names)) + r")(?:['’]s)?"
    period = r"(?:(?:for|in) (?:the )?(?:fiscal )?year|at (?:the )?end of (?:the )?(?:fiscal )?year) (?P<year>(?:19|20)\d{2})"
    metrics = {
        "revenue": r"(?:total )?(?:revenue|net revenue|net sales)",
        "net_income": r"net income(?: \(loss\))?|net profit",
        "operating_income": r"operating income|income from operations",
        "operating_cash_flow": r"operating cash flow|net cash (?:provided by|used in|from) operating activities",
        "total_assets": r"total assets",
        "rd_expense": r"research and development(?: expense)?|r&d(?: expense)?",
        "equity": r"total (?:stockholders|shareholders|shareowners)['’]? equity",
    }
    for metric, words in metrics.items():
        grammar = (
            r"\s*what (?:was|were|is|are) " + company + " (?:" + words + ") " + period + r"[?.]?\s*"
        )
        match = re.fullmatch(grammar, question, re.I)
        if match:
            return Intent(ticker, int(match["year"]), metric)
    spend = (
        r"\s*how much did "
        + company
        + r" spend on (?:research and development|r&d) "
        + period
        + r"[?.]?\s*"
    )
    match = re.fullmatch(spend, question, re.I)
    if match:
        return Intent(ticker, int(match["year"]), "rd_expense")
    return None


def _amount(cell: str, scale: Decimal) -> tuple[Decimal, Decimal] | None:
    cell = re.sub(r"\s*\([a-z]\)\s*$", "", cell.strip(), flags=re.I)
    if not CELL.fullmatch(cell) or FOREIGN.search(cell):
        return None
    if cell.count("(") != cell.count(")") or cell.count("(") > 1:
        return None
    if cell.count("$") > 1:
        return None
    if sum(cell.count(s) for s in ("-", "−", "+")) > 1:
        return None
    if "(" in cell and any(s in cell for s in ("-", "−", "+")):
        return None
    negative = "(" in cell or "-" in cell or "−" in cell
    if negative and "+" in cell:
        return None
    number = re.sub(r"[^\d.]", "", cell)
    try:
        value = Decimal(number) * scale * (-1 if negative else 1)
    except InvalidOperation:
        return None
    places = len(number.rsplit(".", 1)[1]) if "." in number else 0
    return value, scale / (Decimal(10) ** places)


def _normalized_label(text: str) -> str:
    # A semantic qualifier is not a footnote. In particular, retain '(loss)' for
    # the explicit income grammar rather than turning any parenthetical into GAAP.
    return re.sub(r"\s*\((?:[a-z]|\d{1,2})\)", "", text.lower()).strip(" :")


def _label(text: str, metric: str) -> bool:
    return bool(re.fullmatch(LABELS[metric], _normalized_label(text), re.I))


def _company_name(intent: Intent, *, subsidiaries: bool = False) -> str:
    names = {intent.ticker, config.DISPLAY_NAMES.get(intent.ticker, intent.ticker)}
    grammar = (
        r"(?:the )?(?:" + "|".join(re.escape(n) for n in sorted(names)) + r")"
        r"(?:,? (?:Inc\.?|Corporation|Corp\.?|Company|& Co\.?))?"
    )
    return grammar + (r"(?: and Subsidiaries)?" if subsidiaries else "")


def _parent_income(label: str, intent: Intent) -> bool:
    label = _normalized_label(label)
    if (intent.metric not in {"net_income", "equity"} or NONCONTROLLING.search(label)
            or re.search(r"\bcommon\b|\bpreferred\b", label, re.I)):
        return False
    lead = r"net income(?: \(loss\))?" if intent.metric == "net_income" else r"(?:total )?equity"
    if not re.match(lead + r" attributable to\b", label, re.I):
        return False
    entity = re.split("attributable to", label, flags=re.I)[-1].strip()
    company = _company_name(intent)
    owners = r"(?:shareowners|shareholders|stockholders)"
    return bool(re.fullmatch(
        r"(?:" + company + r"|" + owners + r" of " + company
        + r"|" + company + r" " + owners + r"|(?:the )?(?:parent|company))", entity, re.I,
    ))


def _closed_caption_tail(tail: str) -> bool:
    exception_item = (
        r"(?:per[ -]share (?:data|amounts)|par value|percentages|"
        r"shares in (?:thousands|millions)|"
        r"number of shares, which are reflected in (?:thousands|millions))"
    )
    return bool(re.fullmatch(
        r"\s*(?:(?:,?\s*except\s+" + exception_item
        + r"(?:\s*(?:,\s*(?:and\s+)?|and\s+)" + exception_item + r")*)"
        r"|,\s*shares in (?:thousands|millions))?\s*\)?\s*[:.]?\s*",
        tail.split("|", 1)[0], re.I,
    ))


def _closed_caption_prefix(prefix: str) -> bool:
    prefix = prefix.strip().strip("(,; ")
    years = r"(?:19|20)\d{2}(?:,? (?:and )?(?:19|20)\d{2})*"
    return not prefix or bool(re.fullmatch(
        r"(?:shares|units|employees) in (?:thousands|millions|billions)|"
        r"(?:(?:years? ended|as of) )?" + MONTH + r"\.? \d{1,2},?|"
        r"a reconciliation (?:of the company['’]s segment operating income )?"
        r"to the consolidated statements of operations"
        r"(?: follows| for " + years + r" is as follows)|"
        r"the following table shows the computation of basic and diluted earnings per share for "
        + years, prefix, re.I,
    ))


def _caption_scale(text: str, metric: str) -> Decimal | None:
    """Resolve dollar scales, never share/employee/unit scales occurring earlier."""
    if FOREIGN.search(text):
        return None
    scale = r"(thousands?|millions?|billions?|trillions?)"
    # A dollar token must begin a caption clause, not be the suffix of an unknown
    # currency name/symbol. Reject unconsumed dollar mentions rather than skip them.
    monetary = r"(?:u\.?s\.? dollars?|dollars?|USD|u\.?s\.?\s*\$|\$)"
    explicit = list(re.finditer(r"(?:^|[;(,])\s*" + monetary + r"\s+in\s+" + scale, text, re.I))
    mentions = re.finditer(r"\$|\bdollars?\b", text, re.I)
    if any(not any(m.start() <= t.start() and t.end() <= m.end() for m in explicit) for t in mentions):
        return None
    choices = {SCALES[m[1].lower().rstrip("s")] for m in explicit}
    if choices:
        if not _closed_caption_prefix(text[:explicit[0].start()]):
            return None
        if any(not _closed_caption_tail(text[m.end() : explicit[n + 1].start() if n + 1 < len(explicit) else len(text)])
               for n, m in enumerate(explicit)):
            return None
        return next(iter(choices)) if len(choices) == 1 else None
    if metric == "net_income":
        match = re.search(r"\bnet income in\s+" + scale, text, re.I)
        if (match and _closed_caption_prefix(text[:match.start()])
                and re.fullmatch(r"\s*(?:and shares in (?:thousands|millions))?\s*\)?\s*:?\s*",
                                 text[match.end():], re.I)):
            return SCALES[match[1].lower().rstrip("s")]
    match = re.match(r"\s*\(?in\s+" + scale + r"(?=\s*[,)]|\s*$|\s+except\b)", text, re.I)
    if not match:
        match = re.search(r"\(\s*in\s+" + scale + r"(?=\s*[,)]|\s+except\b)", text, re.I)
        if match and re.search(r"\b(?:shares|units|employees)\b", text[: match.start()], re.I):
            return None
    if not match:
        return None
    if not _closed_caption_prefix(text[:match.start()]):
        return None
    # A conventional plain caption has a closed continuation, not an arbitrary
    # comma tail that might name another currency. Limit this to known financial
    # exceptions; unsupported wording falls back rather than claiming USD certainty.
    if not _closed_caption_tail(text[match.end() :]):
        return None
    return SCALES[match[1].lower().rstrip("s")]


def _subannual(text: str) -> bool:
    if QUARTER.search(text):
        return True
    for match in re.finditer(
        r"\b(\d+|[a-z]+(?:-[a-z]+)?)[ -]+(weeks?|months?)\b", text, re.I
    ):
        duration, unit = match[1].lower(), match[2].lower()
        annual = {"52", "53", "fifty-two", "fifty-three"} if unit.startswith("week") else {"12", "twelve"}
        if duration not in annual:
            return True
    return False


def _annual_year_cell(text: str) -> bool:
    return bool(re.fullmatch(
        r"\s*(?:(?:fiscal )?years?(?: ended| ending)?\s+|FY\s*|as of\s+|"
        r"(?:52|53|fifty-two|fifty-three)[ -]+weeks? ended\s+)?"
        r"(?:" + MONTH + r"\.? \d{1,2},?\s+)?(?:19|20)\d{2}"
        r"(?:\s*\((?:[a-z]|\d{1,2})\))?\s*", text, re.I,
    ))


def _table_preamble_start(lines: list[tuple[str, str]], header_i: int) -> int:
    """A completed prior table cannot lend a caption, title or period to this one."""
    for n in range(header_i - 1, -1, -1):
        text = lines[n][0]
        # Literal table-end text may end units/title alignment, but never proves
        # a source gap or clears a governing parent/segment/period qualification.
        if text.strip().lower() == "end of table":
            return n + 1
        if "|" not in text:
            continue
        # A pipe in this table's caption/date metadata is not a prior data row.
        if CAPTION.search(text) and re.fullmatch(
            r"\s*(?:years? ended |as of )?(?:" + MONTH + r"\.? \d{1,2},?)?\s*",
            text.split("|", 1)[1], re.I,
        ):
            continue
        return n + 1
    return 0


def _company_heading(text: str, intent: Intent) -> bool:
    """Company scope requires a whole title, including any entity/period suffix."""
    company = _company_name(intent, subsidiaries=True)
    title = (
        r"(?:selected )?consolidated (?:statements? of (?:changes in )?"
        r"(?:income|operations|comprehensive income|cash flows?|"
        r"(?:stockholders|shareholders|shareowners)['’]? equity)(?: data)?|"
        r"balance sheets?(?: data| analysis)?(?: and cash flows analysis)?|"
        r"cash flows? (?:analysis|statements?)|results(?: of operations)?)|"
        r"summary results of operations|summary of consolidated financial (?:data|statements|results)"
    )
    years = r"(?:19|20)\d{2}(?:,? (?:and )?(?:19|20)\d{2})*"
    period = (
        r"(?: for (?:the )?(?:fiscal )?years?(?: ended| ending)?"
        r"(?: " + MONTH + r"\.? \d{1,2},?)? " + years + r")?"
    )
    return bool(re.fullmatch(
        r"(?:" + company + r" )?(?:" + title + r")(?: of " + company + r")?"
        + period + r"(?: \(continued\))?:?", text.strip(), re.I,
    ))


def _reconciliation_heading(text: str, intent: Intent) -> bool:
    if intent.metric != "operating_income":
        return False
    caption = CAPTION.search(text)
    prefix = text[:caption.start()] if caption else text
    prefix = prefix.strip().strip("(,:; ")
    return bool(re.match(r"a reconciliation\b", prefix, re.I)
                and _closed_caption_prefix(prefix))


def _year_header(text: str) -> bool:
    cells = text.split("|")
    return (len(cells) >= 2 and sum(len(YEAR.findall(x)) == 1 for x in cells) >= 2
            and not any("$" in x or "%" in x or re.search(r"\d,\d{3}", x) for x in cells))


def _data_row(text: str) -> bool:
    cells = [x.strip() for x in text.split("|") if not FOOTNOTE.fullmatch(x.strip())]
    if (len(cells) < 2 or _year_header(text)
            or _annual_year_cell(cells[0]) or CAPTION.search(cells[0])):
        return False
    if re.match(r"(?:years? ended|as of|" + MONTH + r"\.? \d{1,2})\b", cells[0], re.I):
        return False
    return any(
        _amount(cell, Decimal(1)) is not None
        or re.fullmatch(r"[+\-−]?\d+(?:\.\d+)?\s*%|[—–-]", cell)
        for cell in cells[1:]
    )


def _scope_qualified(lines: list[SourceLine], intent: Intent) -> bool:
    """Entity scope outlives rows; captions and year alignment remain table-local.

    A generic balance-sheet/expense heading or rollup cannot erase a qualification.
    Only a closed company title after an intervening table restores company scope.
    An immediate 'Parent Company Only / Consolidated ...' pair stays qualified.
    """
    qualified, subannual, last_qualifier, last_row = False, False, -1, -1
    row_width: int | None = None
    for n, (text, cid) in enumerate(lines):
        text = text.strip()
        if cid is None:
            qualified, subannual, last_qualifier, last_row = False, False, -1, -1
            row_width = None
            continue
        # Period headings/column metadata govern later tables too. A new company
        # title or monetary caption cannot turn a quarter/half-year into a year.
        # A quarter-specific numeric row does not redefine its whole source block.
        if not _data_row(text) and _subannual(text):
            subannual = True
        if "|" in text:
            if _year_header(text):
                cells = [cell.strip() for cell in text.split("|")]
                first_year = next(j for j, cell in enumerate(cells) if len(YEAR.findall(cell)) == 1)
                row_width = len(cells) + (first_year == 0)
            if not _data_row(text):
                metadata = [cell.strip() for cell in text.split("|")
                            if not _annual_year_cell(cell.strip())
                            and not re.fullmatch(r"(?:(?:percentage|percent) )?change", cell.strip(), re.I)]
                # Piped header/caption labels are governing metadata, not numeric
                # rows. Apply the same entity/currency checks as standalone titles.
                if any(
                    QUALIFIED_ENTITY.search(cell) or re.search(r"\bsegments?\b", cell, re.I)
                    or _unknown_nominal_heading(cell, intent)
                    or (re.match(r"(?:selected )?consolidated\b", cell, re.I)
                        and not _company_heading(cell, intent))
                    for cell in metadata
                ):
                    qualified, last_qualifier = True, n
            elif row_width is not None and len([
                cell for cell in text.split("|") if not FOOTNOTE.fullmatch(cell.strip())
            ]) == row_width:
                # Contents/page-reference rows without a governing year header are
                # not financial data and cannot justify clearing a parent scope.
                last_row = n
            continue
        if _company_heading(text, intent) or _reconciliation_heading(text, intent):
            if last_row > last_qualifier:
                qualified = False
            row_width = None
            continue
        rollup = ROLLUP.fullmatch(text.rstrip(":"))
        segment_heading = (re.search(r"\bsegments?\b", text, re.I) and not rollup
                           and (len(text.split()) <= 12 or not text.endswith(".")))
        invalid_company_heading = re.match(
            r"(?:selected )?consolidated\b|summary (?:results|of consolidated)\b", text, re.I
        )
        if (QUALIFIED_ENTITY.search(text) or segment_heading or invalid_company_heading
                or _unknown_nominal_heading(text, intent)):
            qualified, last_qualifier = True, n
            # Region/entity subheads can share the current table's year columns.
            # Unknown prose and a new invalid statement title cannot lend them.
            if invalid_company_heading or not (QUALIFIED_ENTITY.search(text) or segment_heading):
                row_width = None
    return qualified or subannual


def _structural_lead(text: str, intent: Intent | None = None) -> bool:
    text = text.strip().rstrip(":")
    if intent and re.fullmatch(
        _company_name(intent) + r" (?:stockholders|shareholders|shareowners)['’]? equity",
        text, re.I,
    ):
        return True
    return bool(re.fullmatch(
        r"(?:revenues?|cost of revenues?|operations|financing|investing|operating expenses|assets|liabilities|liabilities and "
        r"(?:(?:stockholders|shareholders|shareowners)['’]? )?equity|"
        r"(?:non[ -]?)?current (?:assets|liabilities)|"
        r"(?:stockholders|shareholders|shareowners)['’]? equity|commitments and contingencies|"
        r"(?:cash flows? from )?(?:operating|investing|financing) activities|"
        r"common stock and paid-in capital|retained earnings|"
        r"accumulated other comprehensive (?:income|loss)|"
        r"(?:net cash|cash flows?) (?:provided by|used in|from)"
        r"(?:/?\s*\(?used in\)?)?)", text, re.I,
    ))


def _unknown_dollar_declaration(text: str) -> bool:
    """Do not treat an unrecognized, standalone dollar declaration as USD.

    Numeric source rows/prose do not declare a table's currency. The selected scale
    caption is checked separately with its closed monetary-clause grammar.
    """
    if re.search(r"\d", text) or not re.search(r"\$|\bdollars?\b", text, re.I):
        return False
    declaration = text.strip().strip("()").strip()
    return not re.fullmatch(
        r"(?:u\.?s\.? dollars?|u\.?s\.?\s*\$|USD|dollars?|\$)", declaration, re.I
    )


def _unknown_nominal_heading(text: str, intent: Intent) -> bool:
    """An unsupported short declaration cannot silently supply a currency context.

    Keep a finite set of conventional financial headings/notes. Unknown nominal
    lines such as a standalone currency name require model fallback; this does not
    attempt to enumerate every currency or interpret arbitrary explanatory prose.
    """
    if (_company_heading(text, intent) or _reconciliation_heading(text, intent)
            or _structural_lead(text, intent)):
        return False
    text = text.strip().removesuffix("(continued)").strip().rstrip(".")
    # A short connective fragment ending in a preposition/conjunction is prose,
    # not a nominal entity/currency heading. Explicit entity words are checked
    # independently by the governing-scope guard.
    if re.search(r"\b(?:by|and|or|with|for|to|from|of|in)$", text, re.I):
        return False
    if any(unicodedata.category(c) == "Sc" and c != "$" for c in text):
        return True
    if (CAPTION.search(text) or re.search(r"\d|[|.!?:]", text)
            or len(text.split()) > 6 or not re.fullmatch(r"[\w’'&,/() -]+", text)):
        return False
    financial = (
        r"(?:selected )?consolidated (?:statements? of (?:changes in )?"
        r"(?:income|operations|comprehensive income|cash flows?|(?:stockholders.?|shareholders.?|shareowners.?) equity)(?: data)?"
        r"|balance sheets?(?: data| analysis)?(?: and cash flows analysis)?"
        r"|cash flows? (?:analysis|statements?)|results(?: of operations)?)|"
        r"balance sheets?|income statements?|cash flows? statements?|stockholders.? equity statements?|"
        r"summary results of operations|operating expenses|income tax expense|revenue|"
        r"supplemental(?: accounting)? note|table of contents|part ii|end of table|"
        r"(?:for )?(?:the )?(?:fiscal )?years?(?: ended)?|as of|"
        r"(?:refer to|see) accompanying notes|"
        r"(?:(?:fifty-two|fifty-three)[ -]weeks?|twelve[ -]months?) (?:fiscal )?years? ended|"
        r"cash flows? from (?:operating|investing|financing) activities|"
        r"(?:u\.?s\.? dollars?|u\.?s\.?\s*\$|USD|dollars?|\$)"
    )
    company = _company_name(intent, subsidiaries=True)
    return not (re.fullmatch(financial, text, re.I) or re.fullmatch(company, text, re.I)
                or ROLLUP.fullmatch(text))


def _item_heading(text: str) -> str | None:
    match = re.fullmatch(r"item\s+(\d{1,2}[a-c]?)\s*\.?\s*(.*)", text.strip(), re.I)
    if not match:
        return None
    key, title = match[1].upper(), match[2].strip().lower()
    # A bare 'Item 8' may be a wrapped cross-reference. Require a full recognized
    # title or explicit heading punctuation before resetting source-block scope.
    if not title and not text.strip().endswith("."):
        return None
    titles = {
        "7": "management['’]s discussion and analysis of financial condition and results of operations",
        "7A": "quantitative and qualitative disclosures about market risk",
        "8": "financial statements (?:and|&) supplementary data",
    }
    if title and (key not in titles or not re.fullmatch(titles[key], title, re.I)):
        return None
    return "Item " + key


def _source_lines(group: list[Chunk]) -> list[SourceLine]:
    """Reconstruct only provably contiguous source; discard uncertain exterior lines.

    Legacy fixed indexes used the default220/40word windows. Exact aligned overlap
    recovers complete rows/paragraphs without treating a leading tail as a new label.
    Unknown section edges cannot be guessed. New chunkers record explicit boundaries.
    """
    blocks = []
    for c in group:
        joined = False
        if blocks:
            block = blocks[-1]
            previous = block["last"]
            if previous.chunking_strategy == c.chunking_strategy == "fixed":
                left = list(re.finditer(r"\S+", previous.text))
                right = list(re.finditer(r"\S+", c.text))
                n = OVERLAP_WORDS
                if (
                    len(left) == CHUNK_WORDS
                    and len(right) > n
                    and [m.group() for m in left[-n:]] == [m.group() for m in right[:n]]
                ):
                    block["text"] += c.text[right[n - 1].end() :]
                    joined = True
            elif previous.ends_at_line_boundary is True and c.starts_at_line_boundary is True:
                block["text"] += "\n" + c.text
                joined = True
            elif (
                previous.chunking_strategy == c.chunking_strategy == "section"
                and previous.ends_at_line_boundary is False
                and c.starts_at_line_boundary is False
            ):
                block["text"] += " " + c.text
                joined = True
            if joined:
                block["last"] = c
        if not joined:
            blocks.append({"text": c.text, "first": c, "last": c})
    out = []
    for block in blocks:
        first, last = block["first"], block["last"]
        if out:
            # Unproved gaps cannot inherit a preceding table's units, years or scope.
            out.append(("", None))
        section = first.section
        start = first.starts_at_line_boundary
        if start is None and int(first.id.rsplit("#", 1)[1]) == 0:
            start = True
        lines = block["text"].splitlines()
        for i, line in enumerate(lines):
            if (i == 0 and start is not True) or (
                i == len(lines) - 1 and last.ends_at_line_boundary is not True
            ):
                continue
            heading = _item_heading(line)
            if heading and heading != section:
                # A genuine Item transition can occur inside a legacy chunk whose
                # stored section is stale. Repeated running headers do not reset scope.
                if out:
                    out.append(("", None))
                section = heading
            out.append((line, first.id))
    return out


def _cash_sign(
    label: str, intent: Intent, amount: tuple[Decimal, Decimal]
) -> tuple[Decimal, Decimal]:
    if (
        intent.metric == "operating_cash_flow"
        and re.search(r"used in", label, re.I)
        and not re.search(r"provided|from", label, re.I)
    ):
        return -abs(amount[0]), amount[1]
    return amount


def _groups(chunks: list[Chunk], ticker: str) -> list[list[Chunk]]:
    out: list[list[Chunk]] = []
    for c in sorted(
        (c for c in chunks if c.ticker == ticker),
        key=lambda c: (c.doc_id, int(c.id.rsplit("#", 1)[1])),
    ):
        if (
            out
            and out[-1][-1].doc_id == c.doc_id
            and out[-1][-1].section == c.section
            and int(c.id.rsplit("#", 1)[1]) == int(out[-1][-1].id.rsplit("#", 1)[1]) + 1
        ):
            out[-1].append(c)
        else:
            out.append([c])
    return out


def _fact(
    intent: Intent,
    value: tuple[Decimal, Decimal],
    group: list[Chunk],
    ids: list[str],
    kind: str,
    priority: int,
    details: dict,
) -> Fact:
    ids = list(dict.fromkeys([*ids, *(c.id for c in group)]))
    evidence = [
        {
            "chunk_id": c.id,
            "quote": c.text,
            "source_kind": kind,
            "adjacent_context_supplied": len(group) > 1,
            **details,
        }
        for c in group
        if c.id in ids
    ]
    return Fact(value[0], value[1], intent, ids, evidence, kind, priority)


def _table_facts(intent: Intent, group: list[Chunk]) -> list[Fact]:
    # Parse disconnected source blocks independently: no backward scope/currency/header
    # window may cross an unproved chunk gap, including a dropped qualification line.
    blocks: list[list[tuple[str, str]]] = [[]]
    for text, cid in _source_lines(group):
        if cid is None:
            blocks.append([])
        else:
            blocks[-1].append((text, cid))
    return [fact for block in blocks for fact in _table_block_facts(intent, group, block)]


def _table_rows(lines: list[tuple[str, str]], header_i: int, intent: Intent) -> list[int]:
    """The strict row-alignment frame, shared by every target metric."""
    rows = []
    for n in range(header_i + 1, min(len(lines), header_i + 120)):
        row = lines[n][0]
        if (_subannual(row) or FOREIGN.search(row) or STATEMENT.search(row.strip())
                or (BOUNDARY.search(row.strip())
                    and not re.fullmatch(r"operating expenses", row.strip(), re.I))
                or _year_header(row) or CAPTION.search(row)):
            break
        cells = [x.strip() for x in row.split("|") if not FOOTNOTE.fullmatch(x.strip())]
        if len(cells) < 2:
            if row.strip() and not _structural_lead(row, intent):
                break
        elif not _data_row(row):
            break
        rows.append(n)
    return rows


def _table_has_nci(lines: list[tuple[str, str]], header_i: int) -> bool:
    """Read qualifications below a total, through nonnumeric financial subheads.

    This does not extend positive year-column alignment through prose. A new table,
    statement or entity/period boundary ends the lookahead, so unrelated NCI figures
    in another statement cannot redefine this table's total.
    """
    for n in range(header_i + 1, min(len(lines), header_i + 120)):
        row = lines[n][0]
        if (_year_header(row) or CAPTION.search(row) or STATEMENT.search(row.strip())
                or _subannual(row) or FOREIGN.search(row)
                or (BOUNDARY.search(row.strip())
                    and not re.fullmatch(r"operating expenses", row.strip(), re.I))):
            break
        if "|" in row and not _data_row(row):
            break
        if "|" not in row and QUALIFIED_ENTITY.search(row):
            break
        if NONCONTROLLING.search(row):
            return True
    return False


def _note_or_parent_scope(lines: list[tuple[str, str]]) -> bool:
    """Weak titles cannot establish company totals inside notes or parent accounts."""
    return any(
        ("|" not in text and re.match(
            r"\s*(?:notes? to\b.*\bfinancial statements\b|note\s+\d+\b)", text, re.I,
        ))
        or re.match(
            r"\s*(?:equity in undistributed net income of subsidiaries|"
            r"(?:cash )?dividends (?:from|received from) subsidiaries)\b", text, re.I,
        )
        for text, _ in lines
    )


def _bare_primary_scope(
    lines: list[tuple[str, str]], preamble_start: int, header_i: int, intent: Intent,
) -> bool:
    """A stored Item 8 label alone cannot distinguish statements from note tables.

    Bare titles need a supplied Item 8 heading or an exact table-local company
    line. Note headings and parent-only economic rows invalidate that inference;
    an explicit consolidated title is checked separately by the caller.
    """
    if _note_or_parent_scope(lines[:header_i + 1]):
        return False
    titles = [n for n in range(preamble_start, header_i + 1) if re.fullmatch(
        r"balance sheets?|income statements?|cash flows? statements?|stockholders.? equity statements?",
        lines[n][0].strip(), re.I,
    )]
    if not titles:
        return False
    title_i = titles[-1]
    # Form 10-K running headers can spell Item 8 on a separate, unpunctuated
    # line. Only the complete adjacent PART II / Item 8 / statement-title
    # sequence supplies scope; an isolated cross-reference still cannot do so.
    running_header = (
        title_i >= 2
        and re.fullmatch(r"part ii", lines[title_i - 2][0].strip(), re.I)
        and re.fullmatch(r"item 8", lines[title_i - 1][0].strip(), re.I)
    )
    return bool(
        running_header
        or any(_item_heading(text) == "Item 8" for text, _ in lines[:title_i])
        or any(re.fullmatch(_company_name(intent, subsidiaries=True), text.strip(), re.I)
               for text, _ in lines[preamble_start:title_i])
    )


def _rd_metadata(text: str) -> bool:
    """Every cell between an R&D title and its rows has a closed metadata grammar.

    Check non-year label cells too: a pipe or a long prose label does not make a
    component declaration harmless. Unrecognized prose requires model fallback.
    """
    period = (
        r"(?:(?:for )?(?:the )?(?:fiscal )?years?(?: ended| ending)?|as of|"
        r"(?:52|53|fifty-two|fifty-three)[ -]weeks? ended)"
        r"(?: " + MONTH + r"\.? \d{1,2},?)?"
    )
    return all(
        not cell.strip()
        or _annual_year_cell(cell.strip())
        or _caption_scale(cell.strip(), "rd_expense") is not None
        or re.fullmatch(period + r"|" + MONTH + r"\.? \d{1,2},?|"
                        r"(?:(?:percentage|percent) )?change", cell.strip(), re.I)
        for cell in text.split("|")
    )


def _income_company_title(text: str, intent: Intent) -> bool:
    return bool(_company_heading(text, intent) and re.search(
        r"\b(?:statements? of (?:income|operations)|results(?: of operations)?)\b", text, re.I,
    ))


def _rd_table_scope(
    lines: list[tuple[str, str]], preamble_start: int, header_i: int,
    intent: Intent, primary_statement: bool,
) -> bool:
    """Closed titles plus closed metadata, never a list of forbidden components."""
    if _note_or_parent_scope(lines[:header_i + 1]):
        return False
    titles = [n for n in range(preamble_start, header_i) if (
        _income_company_title(lines[n][0], intent)
        or (primary_statement and re.fullmatch(r"income statements?", lines[n][0].strip(), re.I))
        or re.fullmatch(r"operating expenses", lines[n][0].strip(), re.I)
    )]
    if not titles:
        return False
    title_i = titles[-1]
    if not all(_rd_metadata(text) for text, _ in lines[title_i + 1:header_i + 1]):
        return False
    if re.fullmatch(r"operating expenses", lines[title_i][0].strip(), re.I):
        # A weak subtitle cannot discard a component declaration just because a
        # preceding subtable ended. Require the whole supplied block prefix to
        # be closed metadata/anchors; prior data rows conservatively disqualify it.
        return all(
            _rd_metadata(text)
            or _income_company_title(text, intent)
            or re.fullmatch(_company_name(intent, subsidiaries=True), text.strip(), re.I)
            or _item_heading(text) in {"Item 7", "Item 8"}
            or re.fullmatch(r"part ii|item [78]|income statements?|operating expenses", text.strip(), re.I)
            for text, _ in lines[:title_i]
        )
    return True


def _table_block_facts(
    intent: Intent, group: list[Chunk], lines: list[tuple[str, str]]
) -> list[Fact]:
    facts = []
    for i, (line, cid) in enumerate(lines):
        if not _year_header(line):
            continue
        header = [x.strip() for x in line.split("|")]
        year_cells = [(j, YEAR.findall(x)) for j, x in enumerate(header)]
        year_cells = [(j, int(ys[0])) for j, ys in year_cells if len(ys) == 1]
        if len(year_cells) < 2 or [y for _, y in year_cells].count(intent.year) != 1:
            continue
        if any(not _annual_year_cell(header[j]) for j, _ in year_cells):
            continue
        preamble_start = _table_preamble_start(lines, i)
        preamble = lines[preamble_start : i + 1]
        if _scope_qualified(lines[:i + 1], intent):
            continue
        context = "\n".join(x for x, _ in preamble)
        if FOREIGN.search(context):
            continue
        unit = next(
            (
                (n, CAPTION.search(lines[n][0]))
                for n in range(i, preamble_start - 1, -1)
                if CAPTION.search(lines[n][0])
            ),
            None,
        )
        if unit is None:
            continue
        unit_i, match = unit
        currency_context = context
        if FOREIGN.search(currency_context):
            continue
        if any(
            n != unit_i and (_unknown_dollar_declaration(lines[n][0])
                            or _unknown_nominal_heading(lines[n][0], intent))
            for n in range(preamble_start, i + 1)
        ):
            continue
        if any(
            STATEMENT.search(x.strip()) or BOUNDARY.search(x.strip())
            for x, _ in lines[unit_i + 1 : i + 1]
        ):
            continue
        if _subannual(context):
            continue
        scale = _caption_scale(lines[unit_i][0], intent.metric)
        if scale is None:
            continue
        target = next(j for j, y in year_cells if y == intent.year)
        offset = 1 if year_cells[0][0] == 0 else 0
        table_has_nci = _table_has_nci(lines, i)
        for row_i in _table_rows(lines, i, intent):
            row, row_cid = lines[row_i]
            cells = [x.strip() for x in row.split("|") if not FOOTNOTE.fullmatch(x.strip())]
            if len(cells) < 2:
                continue
            parent_income = _parent_income(cells[0], intent)
            if not _label(cells[0], intent.metric) and not parent_income:
                continue
            if len(cells) != len(header) + offset or target + offset >= len(cells):
                continue
            cash_label = cells[0]
            if (
                intent.metric == "operating_cash_flow"
                and _normalized_label(cells[0]) == "operating activities"
            ):
                leads = [
                    x.strip()
                    for x, _ in lines[max(i, row_i - 4) : row_i]
                    if "|" not in x and re.match(r"\s*(?:net cash|cash flows?)\b", x, re.I)
                ]
                if not leads:
                    continue
                cash_label = leads[-1] + " " + cells[0]
            title_start = preamble_start
            breakers = [
                n
                for n in range(title_start, i + 1)
                if BOUNDARY.search(lines[n][0].strip())
                and not re.fullmatch(r"operating expenses", lines[n][0].strip(), re.I)
            ]
            scope_start = breakers[-1] + 1 if breakers else title_start
            title_lines = preamble
            scope = " ".join(x for x, _ in lines[scope_start : row_i + 1])
            # Entity-qualified headings invalidate every company-wide total, not just cash flow.
            qualifications = " ".join(
                x
                for n, (x, _) in enumerate(
                    lines[preamble_start : row_i + 1], preamble_start
                )
                if n <= i or "|" not in x
            )
            if QUALIFIED_ENTITY.search(qualifications):
                continue
            scope_id = lines[unit_i][1]
            if intent.metric == "operating_cash_flow":
                headings = [
                    n
                    for n in range(preamble_start, i + 1)
                    if (_company_heading(lines[n][0], intent)
                        or re.fullmatch(r"cash flows? statements?", lines[n][0].strip(), re.I))
                    and re.search(r"cash flows?", lines[n][0], re.I)
                ]
                if not headings:
                    continue
                scope_n = headings[-1]
                scoped = " ".join(x for x, _ in lines[preamble_start : row_i + 1])
                if re.search(
                    r"parent company|discontinued operations?|guarantor|condensed consolidating|subsidiary.only|\bsegment\b",
                    scoped,
                    re.I,
                ):
                    continue
                scope_id = lines[scope_n][1]
            consolidated = any(
                _company_heading(x, intent)
                for x, _ in title_lines
            )
            section = next((_item_heading(x) for x, _ in reversed(lines[:i + 1])
                            if _item_heading(x)), group[0].section)
            primary_statement = section == "Item 8" and _bare_primary_scope(
                lines, scope_start, i, intent,
            )
            company_rollup = (
                intent.metric == "revenue"
                and cells[0].lower().strip() == "total net sales"
                and any(
                    ROLLUP.fullmatch(lines[n][0].strip().rstrip(":"))
                    for n in range(title_start, i + 1)
                )
            )
            reconciliation = (
                intent.metric == "operating_income"
                and cells[0].lower().strip() == "total operating income"
                and any(_reconciliation_heading(x, intent) for x, _ in title_lines)
            )
            if breakers and not (consolidated or primary_statement or company_rollup or reconciliation):
                continue
            if intent.metric in {
                "revenue",
                "net_income",
                "total_assets",
                "equity",
                "operating_income",
                "operating_cash_flow",
            }:
                explicit_income_units = intent.metric == "net_income" and re.search(
                    r"net income in (?:thousands?|millions?|billions?)", lines[unit_i][0], re.I
                )
                if not (
                    consolidated
                    or primary_statement
                    or company_rollup
                    or reconciliation
                    or explicit_income_units
                ):
                    continue
            if intent.metric == "rd_expense":
                if (not _rd_table_scope(lines, preamble_start, i, intent, primary_statement)
                        or re.search(r"reconciliation", scope, re.I)):
                    continue
            if (
                intent.metric == "net_income"
                and not parent_income
                and table_has_nci
            ):
                continue
            if intent.metric == "equity" and cells[0].lower().strip() == "total equity":
                if table_has_nci:
                    continue
            amount = _amount(cells[target + offset], scale)
            if amount is None:
                continue
            amount = _cash_sign(cash_label, intent, amount)
            facts.append(
                _fact(
                    intent,
                    amount,
                    group,
                    [scope_id, lines[unit_i][1], cid, row_cid],
                    "table",
                    4 if parent_income else 3,
                    {"period_header": line, "unit_caption": lines[unit_i][0], "metric_row": row},
                )
            )
    return facts


def _narrative_facts(intent: Intent, group: list[Chunk]) -> list[Fact]:
    facts = []
    metric_words = {
        "operating_cash_flow": r"net cash (?:provided by|used in|from) operating activities",
        "revenue": r"(?:total (?:net )?revenues?|total net sales|net operating revenues)",
        "net_income": r"net income",
        "rd_expense": r"research and development(?: expenses?)?",
        "operating_income": r"(?:total )?operating income",
        "total_assets": r"total assets",
        "equity": r"total (?:stockholders.?|shareholders.?|shareowners.?) equity",
    }[intent.metric]
    # The period clause is closed: product/segment/change qualifiers cannot be swallowed.
    date = r"(?:" + MONTH + r"\.? \d{1,2},? )?"
    years_prefix = r"\s+for (?:the )?(?:fiscal )?years?(?: ended| ending)? " + date
    single_prefix = r"\s+(?:for|in|at) (?:the )?(?:fiscal )?(?:year(?: ended)? )?" + date
    name = re.escape(config.DISPLAY_NAMES.get(intent.ticker, intent.ticker))
    subject = r"(?:(?:the )?company['’]s |" + name + r"['’]s )?"
    governing: list[SourceLine] = []
    for line, cid in _source_lines(group):
        if cid is None:
            governing = []
            continue
        governing.append((line, cid))
        if (
            "|" in line or FOREIGN.search(line)
            or _subannual("\n".join(x for x, _ in governing))
            or _scope_qualified(governing, intent)
        ):
            continue
        for metric in re.finditer(metric_words, line, re.I):
            if not re.fullmatch(
                subject, line[: metric.start()].strip() + (" " if metric.start() else ""), re.I
            ):
                continue
            tail = line[metric.end() :]
            paired = re.match(
                years_prefix + r"((?:19|20)\d{2}) and ((?:19|20)\d{2}) (?:was|were|totaled)\s+",
                tail,
                re.I,
            )
            if paired:
                rest = tail[paired.end() :]
                end = re.search(r"\brespectively\b", rest, re.I)
                if end:
                    clause = rest[: end.start()]
                    amounts = list(MONEY.finditer(clause))
                    years = [int(paired[1]), int(paired[2])]
                    if (
                        len(amounts) == 2
                        and years.count(intent.year) == 1
                        and not clause[: amounts[0].start()].strip()
                        and re.fullmatch(
                            r"\s*(?:and|,|,\s*and)\s*",
                            clause[amounts[0].end() : amounts[1].start()],
                            re.I,
                        )
                        and not clause[amounts[1].end() :].strip(" ,")
                    ):
                        token = amounts[years.index(intent.year)].group()
                        amount = _narrative_amount(token)
                        if amount:
                            facts.append(
                                _fact(
                                    intent,
                                    _cash_sign(metric.group(), intent, amount),
                                    group,
                                    [cid],
                                    "respectively",
                                    2,
                                    {"period_header": paired.group(), "metric_row": line},
                                )
                            )
            direct = re.match(
                single_prefix + str(intent.year) + r"\s*(?:was|were|of|totaled|:)\s*", tail, re.I
            )
            if direct:
                rest = tail[direct.end() :]
                amounts = list(MONEY.finditer(rest))
                if (
                    len(amounts) == 1
                    and not rest[: amounts[0].start()].strip()
                    and not rest[amounts[0].end() :].strip(" .,;")
                ):
                    amount = _narrative_amount(amounts[0].group())
                    if amount:
                        facts.append(
                            _fact(
                                intent,
                                _cash_sign(metric.group(), intent, amount),
                                group,
                                [cid],
                                "narrative",
                                2,
                                {"period_header": direct.group(), "metric_row": line},
                            )
                        )
    return facts


def _narrative_amount(token: str) -> tuple[Decimal, Decimal] | None:
    scale = re.search(r"(thousand|million|billion|trillion)", token, re.I)
    number = re.sub(r"(?:thousand|million|billion|trillion)s?", "", token, flags=re.I)
    return _amount(number, SCALES[scale[1].lower()]) if scale else None


def extract_fact(intent: Intent, chunks: list[Chunk]) -> tuple[Fact | None, str]:
    facts = []
    for group in _groups(chunks, intent.ticker):
        facts.extend(_table_facts(intent, group))
        facts.extend(_narrative_facts(intent, group))
    if not facts:
        return None, "no complete supported source layout"
    # Parent-attributable rows identify a different entity scope from a consolidated
    # total including NCI. Otherwise precedence can resolve rounding, not contradictions.
    best = [f for f in facts if f.priority == max(x.priority for x in facts)]
    values = {f.value for f in best}
    if len(values) != 1:
        return None, "conflicting source facts"
    chosen = min(best, key=lambda f: (f.unit_step, len(f.citations), f.citations))
    parent_precedence = False
    for other in facts:
        if other in best:
            continue
        if chosen.priority == 4 and other.priority == 3 and other.kind == "table":
            parent_precedence = True
            continue
        if abs(chosen.value - other.value) > other.unit_step / 2:
            return None, "conflicting source facts"
    note = "explicit metric, period, unit and sign"
    if parent_precedence:
        note += "; explicit parent-attributable row takes precedence over generic consolidated totals"
    return chosen, note
